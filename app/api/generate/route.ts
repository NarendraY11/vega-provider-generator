import { NextResponse } from 'next/server';
import JSZip from 'jszip';
import { generateProvider } from '../../../lib/generator';

export async function POST(req: Request) {
  try {
    const body = await req.json();
    const analysis = body?.analysis;
    const name = String(body?.name || analysis?.title || 'Website Provider').trim().slice(0, 80);
    if (!analysis?.url) return NextResponse.json({ error: 'Analysis is required' }, { status: 400 });
    if (!/^https?:\/\//i.test(analysis.url)) return NextResponse.json({ error: 'Analysis URL is invalid.' }, { status: 400 });
    if (!name) return NextResponse.json({ error: 'Provider name is required.' }, { status: 400 });

    const result = generateProvider(analysis, name);
    const zip = new JSZip();
    for (const [path, content] of Object.entries(result.files)) zip.file(path, content);
    zip.file('GENERATOR-NOTES.md', `Generated by Vega Provider Generator 2.0.\n\nSource: ${analysis.url}\nCrawled pages: ${analysis.crawledPages || 1}\n\nThe ZIP intentionally contains manifest-entry.json instead of replacing a repository's root manifest.json. Merge that entry into your existing manifest, then build the official provider repository so dist/ is generated.\n`);
    const blob = await zip.generateAsync({ type: 'base64' });
    return NextResponse.json({ filename: `${result.id}-vega-provider.zip`, base64: blob, files: Object.keys(result.files), version: '2.0' });
  } catch (e) {
    return NextResponse.json({ error: String(e instanceof Error ? e.message : e) }, { status: 500 });
  }
}
